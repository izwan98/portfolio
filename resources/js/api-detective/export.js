import { example, requestExample, typeLabel } from './schema.js';

const cell = (v) => String(v ?? '').replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');

function groupByTag(endpoints) {
    const groups = new Map();
    for (const e of endpoints) {
        const tag = e.tags?.[0] || 'other';
        if (!groups.has(tag)) groups.set(tag, []);
        groups.get(tag).push(e);
    }
    return groups;
}

export function toMarkdown(api, tests = {}) {
    const refs = api.refs || {};
    const out = [];

    out.push(`# ${api.title}${api.version ? ` (v${api.version})` : ''}`, '');
    if (api.overview) out.push(api.overview, '');
    out.push(`- **Source:** ${api.source.kind}${api.source.specVersion ? ` ${api.source.specVersion}` : ''}${api.source.url ? ` — ${api.source.url}` : ''}`);
    if (api.servers?.length) out.push(`- **Base URL${api.servers.length > 1 ? 's' : ''}:** ${api.servers.map((s) => `\`${s.url}\``).join(', ')}`);
    out.push(`- **Auth:** ${api.authNotes || 'No authentication is documented.'}`);
    out.push(`- **Endpoints:** ${api.endpoints.length}`, '');

    for (const [tag, endpoints] of groupByTag(api.endpoints)) {
        const tagInfo = api.tags?.find((t) => t.name === tag);
        out.push(`## ${tag}`, '');
        if (tagInfo?.description) out.push(tagInfo.description, '');

        for (const e of endpoints) {
            out.push(`### \`${e.method} ${e.path}\`${e.deprecated ? ' _(deprecated)_' : ''}`, '');
            if (e.doc?.summary) out.push(`**${e.doc.summary}**`, '');
            if (e.doc?.details) out.push(e.doc.details, '');
            if (e.doc?.tips?.length) out.push(...e.doc.tips.map((t) => `> 💡 ${t}`), '');

            if (e.parameters?.length) {
                out.push('| Parameter | In | Type | Required | Description |', '|---|---|---|---|---|');
                for (const p of e.parameters) {
                    out.push(`| \`${cell(p.name)}\` | ${p.in} | ${cell(typeLabel(p.schema, refs))} | ${p.required ? 'yes' : 'no'} | ${cell(p.description)} |`);
                }
                out.push('');
            }

            if (e.requestBody) {
                const body = e.requestBody.example ?? (e.requestBody.schema ? requestExample(e.requestBody.schema, refs) : null);
                out.push(`**Request body** (${e.requestBody.contentType || 'application/json'}${e.requestBody.required ? ', required' : ''}): \`${typeLabel(e.requestBody.schema, refs)}\``, '');
                if (body !== null && body !== undefined) out.push('```json', JSON.stringify(body, null, 2), '```', '');
            }

            if (e.responses?.length) {
                out.push('| Status | Description | Body |', '|---|---|---|');
                for (const r of e.responses) out.push(`| ${r.status} | ${cell(r.description)} | ${r.schema ? `\`${cell(typeLabel(r.schema, refs))}\`` : ''} |`);
                out.push('');
            }

            const t = tests[e.id];
            if (t?.response) {
                out.push(`_Last tested: ${t.response.status ?? 'error'} ${t.response.reason ?? ''} in ${t.response.timeMs ?? '?'} ms${t.validation ? ` — schema check: ${t.validation.ok ? 'passed' : `${t.validation.issues.length} issue(s)`}` : ''}._`, '');
            }
        }
    }

    out.push('---', `_Generated by API Detective on ${new Date().toISOString().slice(0, 10)}._`, '');
    return out.join('\n');
}

export function toJson(api, tests = {}, log = []) {
    const refs = api.refs || {};

    return JSON.stringify(
        {
            generator: 'API Detective',
            generatedAt: new Date().toISOString(),
            api: {
                title: api.title,
                version: api.version,
                description: api.description,
                overview: api.overview,
                authNotes: api.authNotes,
                source: api.source,
                servers: api.servers,
                auth: api.auth,
                tags: api.tags,
            },
            endpoints: api.endpoints.map((e) => ({
                ...e,
                exampleRequestBody: e.requestBody ? (e.requestBody.example ?? (e.requestBody.schema ? requestExample(e.requestBody.schema, refs) : null)) : undefined,
                exampleResponses: Object.fromEntries((e.responses || []).filter((r) => r.schema || r.example).map((r) => [r.status, r.example ?? example(r.schema, refs)])),
                lastTest: tests[e.id]?.response
                    ? { status: tests[e.id].response.status, timeMs: tests[e.id].response.timeMs, schemaCheck: tests[e.id].validation ?? null }
                    : undefined,
            })),
            schemas: refs,
            discoveryLog: log,
        },
        null,
        2,
    );
}

export function download(filename, text, type) {
    const blob = new Blob([text], { type });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
}

export function slug(text) {
    return String(text || 'api').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') || 'api';
}
